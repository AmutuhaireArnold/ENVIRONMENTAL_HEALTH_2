      function initials(str){
        return (str||'').replace(/[^A-Za-z0-9]/g,'').slice(0,4).toUpperCase();
      }

      // ---- Render the 11 circular logo buttons ----
      var assocGrid = document.getElementById('assocGrid');
      if(assocGrid){
        ASSOCIATIONS.forEach(function(a){
          var btn = document.createElement('button');
          btn.type = 'button';
          btn.className = 'assoc-item';
          btn.setAttribute('data-assoc-id', a.id);
          btn.innerHTML =
            '<span class="assoc-logo-circle">' +
              '<img src="/images/'+a.logo+'" alt="'+a.name+' logo" onerror="this.replaceWith(Object.assign(document.createElement(\'span\'),{className:\'fallback-initials\',textContent:\''+initials(a.short)+'\'}))">' +
            '</span>' +
            '<span class="assoc-full-name">'+a.name+'</span>' +
            '<span class="assoc-shortname-btn">'+a.short+'</span>';
          btn.addEventListener('click', function(){ openChart(a.id); });
          assocGrid.appendChild(btn);
        });
      }

      // ---- Build one chart "card" (used for both the president and officers) ----
      function buildCard(person, isPresident){
        var card = document.createElement('div');
        card.className = 'chart-card';
        card.innerHTML =
          '<div class="post-bar">'+person.post+'</div>' +
          '<div class="photo-wrap"><img src="/images/'+person.photo+'" alt="'+person.name+'"></div>' +
          '<div class="card-text"><h4>'+person.name+'</h4><p>'+person.school+'</p></div>';
        card.querySelector('.photo-wrap').addEventListener('click', function(){
          openChartPhoto(person, isPresident ? 'president' : 'officers');
        });
        return card;
      }

      // ---- Open / close the association chart modal ----
      var chartModal = document.getElementById('chartModal');
      var chartHeaderLogo = document.getElementById('chartHeaderLogo');
      var chartHeaderShort = document.getElementById('chartHeaderShort');
      var chartHeaderName = document.getElementById('chartHeaderName');
      var chartPresidentEl = document.getElementById('chartPresident');
      var chartOfficersEl = document.getElementById('chartOfficers');
      var currentAssoc = null;
      var chartLastFocused = null;

      function openChart(id){
        var a = ASSOCIATIONS.filter(function(x){ return x.id===id; })[0];
        if(!a) return;
        currentAssoc = a;

        chartHeaderLogo.innerHTML = '<img src="/images/'+a.logo+'" alt="'+a.name+' logo" onerror="this.replaceWith(Object.assign(document.createElement(\'span\'),{className:\'fallback-initials\',textContent:\''+initials(a.short)+'\'}))">';
        chartHeaderShort.textContent = a.short + ' · NATIONAL EXECUTIVE COMMITTEE';
        chartHeaderName.textContent = a.name;

        chartPresidentEl.innerHTML = '';
        chartPresidentEl.appendChild(buildCard(a.president, true));

        chartOfficersEl.innerHTML = '';
        a.officers.forEach(function(o){ chartOfficersEl.appendChild(buildCard(o, false)); });

        chartLastFocused = document.activeElement;
        chartModal.classList.add('open');
        chartModal.setAttribute('aria-hidden','false');
        document.body.classList.add('modal-open');
        chartModal.querySelector('.chart-modal-close').focus();
      }
      function closeChart(){
        chartModal.classList.remove('open');
        chartModal.setAttribute('aria-hidden','true');
        document.body.classList.remove('modal-open');
        if(chartLastFocused) chartLastFocused.focus();
      }
      if(chartModal){
        chartModal.querySelectorAll('[data-chart-close]').forEach(function(el){ el.addEventListener('click', closeChart); });
      }

      // ---- Photo zoom lightbox for people inside a chart ----
      var chartPhotoModal = document.getElementById('chartPhotoModal');
      var chartPhotoImg = document.getElementById('chartPhotoImg');
      var chartPhotoName = document.getElementById('chartPhotoName');
      var chartPhotoPost = document.getElementById('chartPhotoPost');
      var chartPhotoPrev = document.getElementById('chartPhotoPrev');
      var chartPhotoNext = document.getElementById('chartPhotoNext');
      var photoGroup = [];
      var photoIndex = 0;
      var photoLastFocused = null;

      function renderChartPhoto(){
        var person = photoGroup[photoIndex];
        if(!person) return;
        var photoSrc = person.photo && person.photo.indexOf('/images/') === 0 ? person.photo : '/images/' + person.photo;
        chartPhotoImg.src = photoSrc;
        chartPhotoImg.alt = person.name;
        chartPhotoName.textContent = person.name;
        chartPhotoPost.textContent = person.post + ' — ' + person.school;
        chartPhotoPrev.disabled = photoGroup.length < 2;
        chartPhotoNext.disabled = photoGroup.length < 2;
      }
      function openChartPhoto(person){
        if(!currentAssoc) return;
        photoGroup = [currentAssoc.president].concat(currentAssoc.officers);
        photoIndex = photoGroup.indexOf(person);
        if(photoIndex < 0) photoIndex = 0;
        photoLastFocused = document.activeElement;
        chartPhotoModal.classList.add('open');
        chartPhotoModal.setAttribute('aria-hidden','false');
        renderChartPhoto();
        chartPhotoModal.querySelector('.chart-photo-modal-close').focus();
      }
      function closeChartPhoto(){
        chartPhotoModal.classList.remove('open');
        chartPhotoModal.setAttribute('aria-hidden','true');
        if(photoLastFocused) photoLastFocused.focus();
      }
      function stepChartPhoto(dir){
        if(photoGroup.length < 2) return;
        photoIndex = (photoIndex + dir + photoGroup.length) % photoGroup.length;
        renderChartPhoto();
      }
      if(chartPhotoModal){
        chartPhotoModal.querySelectorAll('[data-chart-photo-close]').forEach(function(el){ el.addEventListener('click', closeChartPhoto); });
        chartPhotoPrev.addEventListener('click', function(){ stepChartPhoto(-1); });
        chartPhotoNext.addEventListener('click', function(){ stepChartPhoto(1); });
      }

      document.addEventListener('keydown', function(e){
        if(chartPhotoModal && chartPhotoModal.classList.contains('open')){
          if(e.key==='Escape') closeChartPhoto();
          if(e.key==='ArrowLeft') stepChartPhoto(-1);
          if(e.key==='ArrowRight') stepChartPhoto(1);
          return;
        }
        if(chartModal && chartModal.classList.contains('open')){
          if(e.key==='Escape') closeChart();
        }
      });

})();
